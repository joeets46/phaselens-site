// Generates public/third-party-notices.txt from the LICENSE (and NOTICE) files in node_modules.
// Run: node scripts/generate-notices.mjs
// BUNDLED is the list of packages whose code or CSS/fonts end up in dist/. It was checked against a
// production build's sourcemap (JS) and the CSS/font imports; re-check it when dependencies change.
import { readFileSync, readdirSync, writeFileSync } from "node:fs"

const BUNDLED = [
  "react", "react-dom", "scheduler",
  "@radix-ui/react-slot", "@radix-ui/react-compose-refs",
  "class-variance-authority", "clsx", "cn", "lucide-react",
  "@paper-design/shaders-react", "@paper-design/shaders",
  "tailwindcss", "tw-animate-css", "shadcn", // CSS only (stylesheet inputs)
  "@fontsource-variable/archivo", // the Archivo variable font files
]

const find = (dir, re) => readdirSync(dir).find((f) => re.test(f))
const groups = new Map() // license text -> packages
const notices = new Map() // package -> NOTICE text
for (const name of BUNDLED) {
  const dir = `node_modules/${name}`
  const pkg = JSON.parse(readFileSync(`${dir}/package.json`, "utf8"))
  const text = readFileSync(`${dir}/${find(dir, /^licen[sc]e/i)}`, "utf8").replace(/\r\n/g, "\n").trim()
  const g = groups.get(text) ?? { pkgs: [] }
  g.pkgs.push(`${name} ${pkg.version} (${pkg.license})`)
  groups.set(text, g)
  const n = find(dir, /^notice/i)
  if (n) notices.set(name, readFileSync(`${dir}/${n}`, "utf8").replace(/\r\n/g, "\n").trim())
}

const rule = "-".repeat(73)
let out = `Third-party notices for the PhaseLens site
===========================================

This site bundles the open-source packages listed below. Each group of
packages is followed by the license text shipped with it. Generated by
scripts/generate-notices.mjs; do not edit by hand.
`
for (const [text, g] of groups) {
  out += `\n${rule}\n${g.pkgs.map((p) => `  - ${p}`).join("\n")}\n${rule}\n\n${text}\n`
}
if (notices.size) {
  out += `\n${rule}\nNOTICE files (reproduced as required by Apache-2.0 section 4(d))\n${rule}\n`
  for (const [name, text] of notices) out += `\n[${name}]\n${text}\n`
  out += `\nSource: https://github.com/paper-design/shaders\n`
}
out += `\n${rule}\nData\n${rule}\n
Match data shown on this site is StatsBomb Open Data (https://github.com/hudl/open-data),
used under the StatsBomb Open Data User Agreement. StatsBomb is a trademark of its owner.
`
writeFileSync("public/third-party-notices.txt", out.replace(/\n/g, "\r\n").replace(/\r\n/g, "\n"))
console.log(`${BUNDLED.length} packages, ${groups.size} license texts`)
